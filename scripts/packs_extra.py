PX = 10  # svg units per pixel


def pixel_svg(rows):
    """Row runs as rects; crispEdges avoids seams between pixels when scaled."""
    w, h = len(rows[0]) * PX, len(rows) * PX
    rects = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            c = row[x]
            run = 1
            while x + run < len(row) and row[x + run] == c:
                run += 1
            if c != ".":
                rects.append(f'<rect x="{x*PX}" y="{y*PX}" width="{run*PX}" height="{PX}" fill="{PAL[c]}"/>')
            x += run
    return w, h, f'<g shape-rendering="crispEdges">{"".join(rects)}</g>'


